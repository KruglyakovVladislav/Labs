"""
Почему цикл завершится и почему range(a, b) не всегда соответствует условию задания №1?
-Потому, что range(a, b) включает a, но не включает b.
Пример
Задание: «вывести числа от 1 до 4 включительно»
Неправильно: range(1, 4) → даст 1, 2, 3 (число 4 пропущено).
Правильно: range(1, 5) → 1, 2, 3, 4.
Задание: «просуммировать числа от a до b включительно»
Если написать for x in range(a, b):, то число b не войдёт в сумму.
Нужно писать range(a, b + 1).
Обратный порядок (убывание)
Для range(a, b, -1) тоже действует правило «верхняя граница не включается».
Например, range(4, 1, -1) даст 4, 3, 2 (число 1 не войдёт).
Чтобы включить 1, нужно range(4, 0, -1) → 4, 3, 2, 1.
Поэтому в  задачах (range_numbers.py; statistics.py) приходилось корректировать границы: b + 1 для возрастания и b - 1 для убывания.
"""